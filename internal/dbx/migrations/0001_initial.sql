INSERT INTO playlist_revisions (id, is_draft, created_at, created_by, note)
VALUES (1, 1, strftime('%Y-%m-%dT%H:%M:%SZ','now'), 'system', 'initial draft');

INSERT INTO schedule_rules (kind, weekday, enabled, on_time, off_time, label, created_at, updated_at)
SELECT 'weekly', d.wd, 1, '08:00', '17:00', '',
       strftime('%Y-%m-%dT%H:%M:%SZ','now'), strftime('%Y-%m-%dT%H:%M:%SZ','now')
FROM (SELECT 0 AS wd UNION SELECT 1 UNION SELECT 2 UNION SELECT 3
      UNION SELECT 4 UNION SELECT 5 UNION SELECT 6) AS d;
